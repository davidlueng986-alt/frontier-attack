def g6_decode(line: str):
    """Decode one graph6 line into (n, sorted edge list).  n <= 32."""
    b = line.encode("ascii")
    if not b:
        raise ValueError("empty graph6 line")
    first = b[0]
    if first < 63:
        n = first
        body = b[1:]
    elif first == 63:
        raise ValueError("n >= 63 unsupported")
    else:
        n = first - 63
        body = b[1:]
    if not 1 <= n <= 32:
        raise ValueError(f"bad n={n}")
    bits = n * (n - 1) // 2
    x = 0
    for ch in body:
        x = (x << 6) | ((ch - 63) & 63)
    pad = len(body) * 6 - bits
    if pad < 0:
        raise ValueError("short graph6 body")
    if pad:
        x >>= pad
    edges = []
    pos = bits - 1
    for j in range(1, n):
        for i in range(j):
            if (x >> pos) & 1:
                edges.append((i, j))
            pos -= 1
    return n, edges


def open_text(path: Path):
    with open(path, "rb") as f:
        magic = f.read(2)
    if magic == b"\x1f\x8b":
        return gzip.open(path, "rt", encoding="ascii")
    return open(path, "r", encoding="ascii")


