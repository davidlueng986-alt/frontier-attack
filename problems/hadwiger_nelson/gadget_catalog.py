def adj_bits(n: int, edges) -> list[int]:
    adj = [0] * n
    for a, b in edges:
        adj[a] |= 1 << b
        adj[b] |= 1 << a
    return adj


def has_k4(n: int, adj) -> bool:
    for b in range(n):
        for c in range(b + 1, n):
            if not (adj[b] >> c) & 1:
                continue
            common = adj[b] & adj[c]
            verts = []
            x = common
            while x:
                lb = x & -x
                verts.append(lb.bit_length() - 1)
                x ^= lb
            for i in range(len(verts)):
                for j in range(i + 1, len(verts)):
                    if (adj[verts[i]] >> verts[j]) & 1:
                        return True
    return False


def structural(n: int, edges, u: int, v: int) -> dict:
    adj = adj_bits(n, edges)
    max_common = 0
    for i in range(n):
        for j in range(i + 1, n):
            c = (adj[i] & adj[j]).bit_count()
            if c > max_common:
                max_common = c
    tri3 = sum((adj[a] & adj[b]).bit_count() for a, b in edges)
    return {
        "m": len(edges),
        "k4": has_k4(n, adj),
        "max_common": max_common,
        "triangles": tri3 // 3,
        "edge_in_3_triangles": tri3 > 2 * len(edges),
        "uv_adjacent": bool((adj[u] >> v) & 1),
    }


# ---------------------------------------------------------------------------
# stage 3d: certified circle-intersection embedding, |uv|^2 = 3
# ---------------------------------------------------------------------------

iv.dps = 40
IV_ZERO = iv.mpf(0)
IV_ONE = iv.mpf(1)
IV_SQ3 = iv.sqrt(3)


def _dist2(p, q):
    return (p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2


def _overlaps_one(x) -> bool:
    return not (x.b < IV_ONE.a or x.a > IV_ONE.b)


def embed_order(n: int, edges, u: int, v: int):
    adj = [set() for _ in range(n)]
    for a, b in edges:
        adj[a].add(b)
        adj[b].add(a)
    order = [u, v]
    placed = {u, v}
    while len(order) < n:
        rest = [w for w in range(n) if w not in placed]
        best = max(rest, key=lambda w: (len(adj[w] & placed), len(adj[w]), -w))
        if len(adj[best] & placed) < 2:
            return None, adj
        order.append(best)
        placed.add(best)
    return order, adj


def certify_no_embedding(n: int, edges, u: int, v: int,
                         node_cap: int = 400_000, time_cap: float = 30.0) -> dict:
    """Sound certificate.  Returns status in
    {CERTIFIED-EXCLUDED, PLACEMENT-FOUND, CAPPED, NON-RIGID-ORDER, BAD-TERMINALS}.
    Exhaustion with no complete placement certifies that no placement of the
    vertices with every edge of length 1 and |uv|^2 = 3 exists.
    """
    t0 = time.time()
    adj = [set() for _ in range(n)]
    for a, b in edges:
        adj[a].add(b)
        adj[b].add(a)
    if v in adj[u]:
        return {"status": "BAD-TERMINALS", "nodes": 0, "seconds": 0.0}
    order, adj = embed_order(n, edges, u, v)
    if order is None:
        return {"status": "NON-RIGID-ORDER", "nodes": 0, "seconds": 0.0}

    pos = {u: (IV_ZERO, IV_ZERO), v: (IV_SQ3, IV_ZERO)}
    nodes = 0
    capped = False
    ambiguity = False

    def dfs(k: int, mirror_used: bool) -> bool:
        nonlocal nodes, capped, ambiguity
        nodes += 1
        if nodes > node_cap or time.time() - t0 > time_cap:
            capped = True
            return True
        if k == len(order):
            ambiguity = True
            return True
        w = order[k]
        anchors = [x for x in order[:k] if x in adj[w]]
        pair = None
        for i in range(len(anchors)):
            for j in range(i + 1, len(anchors)):
                d2 = _dist2(pos[anchors[i]], pos[anchors[j]])
                if d2.a > 0:
                    pair = (anchors[i], anchors[j])
                    break
            if pair:
                break
        if pair is None:
            ambiguity = True
            return True
        a, b = pair
        others = [x for x in anchors if x not in pair]
        pa, pb = pos[a], pos[b]
        d2 = _dist2(pa, pb)
        d = iv.sqrt(d2)
        x = d2 / (2 * d)          # r1 = r2 = 1
        h2 = IV_ONE - x * x
        if h2.b < 0:
            return False
        h2c = iv.mpf([h2.a if h2.a > 0 else 0, h2.b])
        h = iv.sqrt(h2c)
        ux = (pb[0] - pa[0]) / d
        uy = (pb[1] - pa[1]) / d
        bx = pa[0] + x * ux
        by = pa[1] + x * uy
        for sgn in (1, -1):
            p = (bx - sgn * h * uy, by + sgn * h * ux)
            if not mirror_used and p[1].b < 0:
                continue
            m2 = mirror_used or p[1].a > 0 or p[1].b < 0
            ok = True
            for o in others:
                if not _overlaps_one(_dist2(p, pos[o])):
                    ok = False
                    break
            if ok:
                pos[w] = p
                if dfs(k + 1, m2):
                    return True
                del pos[w]
            if h2c.b == 0:
                break
        return False

    complete = dfs(2, False)
    if capped:
        status = "CAPPED"
    elif complete:
        status = "PLACEMENT-FOUND" if ambiguity else "CAPPED"
    else:
        status = "CERTIFIED-EXCLUDED"
    return {"status": status, "nodes": nodes, "seconds": round(time.time() - t0, 3)}


