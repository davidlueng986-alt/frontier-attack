    t_start = time.time()
    log = Log(LOG_PATH)
    log("run", "gadget_catalog.py start (abstract catalog -> geometric filter)")

    cache = Path(args.catalog_dir) if args.catalog_dir else (
        Path(os.environ.get("TEMP", "/tmp")) / "opencode" / "hn_crit_catalog")

    # ---- stage 1 ---------------------------------------------------------
